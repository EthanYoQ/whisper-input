pub fn dictation(mode: PolishMode) -> &'static str {
    match mode {
        PolishMode::Raw => RAW,
        PolishMode::Light => LIGHT,
        PolishMode::Structured => STRUCTURED,
        PolishMode::Formal => FORMAL,
    }
}

pub fn selection(mode: PolishMode) -> &'static str {
    match mode {
        PolishMode::Raw => SELECTION_RAW,
        PolishMode::Light => SELECTION_LIGHT,
        PolishMode::Structured => SELECTION_STRUCTURED,
        PolishMode::Formal => SELECTION_FORMAL,
    }
}

